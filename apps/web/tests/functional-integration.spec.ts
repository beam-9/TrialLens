import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";

test.describe("isolated UI to proxy to API functionality", () => {
  test.skip(process.env.TRIALLENS_FUNCTIONAL_TESTS !== "1", "Requires the isolated frozen-fixture API with outbound inference blocked");

  test("validates workspace fields and bounds research questions", async ({ page }) => {
    await page.goto("/");
    const condition = page.getByLabel("Condition", { exact: true });
    const build = page.getByRole("button", { name: "Build workspace", exact: true });
    await condition.fill(" ");
    await expect(build).toBeDisabled();
    await condition.fill("x");
    await expect(build).toBeDisabled();
    await condition.fill("valid condition");
    await expect(build).toBeEnabled();
    await expect(condition).toHaveAttribute("maxlength", "120");
    await expect(condition).toHaveAttribute("required", "");
    await expect(page.getByLabel("Drug or intervention", { exact: true })).toHaveAttribute("maxlength", "120");
    await page.getByRole("tab", { name: "Ask", exact: true }).click();
    await expect(page.locator("#ask-question")).toHaveAttribute("maxlength", "500");
    await expect(page.getByRole("button", { name: "Answer with citations", exact: true })).toBeDisabled();
  });

  test("persists created evidence, reviewed rows, scoped follow-ups and exported brief", async ({ page }) => {
    await page.goto("/");
    const condition = `browser integration ${Date.now()}`;
    await page.getByLabel("Condition", { exact: true }).fill(condition);
    await page.getByLabel("Drug or intervention", { exact: true }).fill("intervention A");
    const createdResponse = page.waitForResponse(response => response.url().endsWith("/api/workspaces") && response.request().method() === "POST");
    await page.getByRole("button", { name: "Build workspace", exact: true }).click();
    const workspace = await (await createdResponse).json();
    await expect(page.getByRole("table")).toBeVisible();
    await expect(page.getByRole("row")).toHaveCount(3);
    const base = `/api/workspaces/${workspace.id}`;
    expect((await (await page.request.get(`${base}/sources`)).json()).length).toBe(2);

    await page.getByRole("button", { name: "Source filter: Literature", exact: true }).click();
    await expect(page.getByRole("row")).toHaveCount(2);
    await page.getByRole("button", { name: "Inspect", exact: true }).click();
    const dialog = page.getByRole("dialog");
    await expect(dialog).toContainText("Supporting quote");
    await expect(dialog).toContainText("PubMed:EVAL-FILTER-PUBLICATION");
    const review = page.waitForResponse(response => response.request().method() === "PATCH" && response.url().includes("/extractions/"));
    await dialog.getByRole("button", { name: "Mark reviewed", exact: true }).click();
    expect((await review).status()).toBe(200);
    await expect(dialog).toContainText("Checked");
    await page.keyboard.press("Escape");
    await expect(dialog).toBeHidden();
    await page.getByRole("button", { name: "Review filter: Checked", exact: true }).click();
    await expect(page.getByRole("row")).toHaveCount(2);
    await page.getByRole("button", { name: "Review filter: Not checked", exact: true }).click();
    await expect(page.getByRole("table")).toBeHidden();
    await page.getByRole("button", { name: "Review filter: Any status", exact: true }).click();
    await page.getByRole("button", { name: "Source filter: All", exact: true }).click();
    await expect(page.getByRole("row")).toHaveCount(3);
    await page.getByRole("button", { name: "Filter: only rows with numbers", exact: true }).click();
    await expect(page.getByRole("button", { name: "Filter: only rows with numbers", exact: true })).toHaveAttribute("aria-pressed", "true");
    await page.getByRole("button", { name: "Filter: only rows with numbers", exact: true }).click();

    await page.getByRole("tab", { name: "Sources", exact: true }).click();
    await expect(page.getByRole("tabpanel", { name: "Sources", exact: true })).toContainText("Synthetic evaluation control: publication");
    await page.getByRole("tab", { name: "Brief", exact: true }).click();
    await expect(page.getByRole("button", { name: "Export brief", exact: true })).toBeDisabled();
    await page.getByRole("tab", { name: "Ask", exact: true }).click();
    await page.getByLabel("Sources for this conversation").selectOption("pubmed");
    await page.locator("#ask-question").fill("What symptom result does the publication report?");
    const firstResponse = page.waitForResponse(response => response.url().endsWith("/ask") && response.request().method() === "POST");
    await page.getByRole("button", { name: "Answer with citations", exact: true }).click();
    const first = await (await firstResponse).json();
    expect(first.generation_mode).toBe("conversational");
    expect(first.source_types).toEqual(["pubmed"]);
    expect(first.citations).toEqual(["PubMed:EVAL-FILTER-PUBLICATION"]);
    expect(first.retrieved_chunks.every((chunk: {source_type: string}) => chunk.source_type === "pubmed")).toBe(true);
    await expect(page.locator("#answer-result")).toContainText("deterministic browser integration response");
    await page.getByLabel("Ask a follow-up").fill("Explain that more simply");
    const followResponse = page.waitForResponse(response => response.url().endsWith("/ask") && response.request().method() === "POST");
    await page.getByRole("button", { name: "Ask follow-up", exact: true }).click();
    const follow = await (await followResponse).json();
    expect(follow.previous_answer_id).toBe(first.id);
    expect(follow.source_types).toEqual(["pubmed"]);
    await expect(page.locator("#answer-result")).toContainText("Explain that more simply");
    await page.locator("#answer-result").locator("..").getByRole("button", { name: "Save to brief", exact: true }).click();
    await expect(page.getByRole("button", { name: "Remove from brief", exact: true })).toBeVisible();
    await page.getByRole("tab", { name: "Brief", exact: true }).click();
    await expect(page.locator(".brief-saved-answer")).toContainText("Explain that more simply");
    const downloadEvent = page.waitForEvent("download");
    await page.getByRole("button", { name: "Export brief", exact: true }).click();
    const download = await downloadEvent;
    expect(download.suggestedFilename()).toBe("triallens-research-brief.md");
    const downloadedPath = await download.path();
    expect(downloadedPath).toBeTruthy();
    const markdown = await readFile(downloadedPath!, "utf8");
    expect(markdown).toContain("Explain that more simply");
    expect(markdown).toContain("PubMed:EVAL-FILTER-PUBLICATION");
    expect(markdown).toContain("Evidence gaps");

    await page.reload();
    await page.locator(".recent-workspace-button").filter({ hasText: condition }).click();
    await expect(page.locator(".workspace-context")).toContainText(condition);
    const rows = await (await page.request.get(`${base}/extractions`)).json();
    expect(rows.find((row: {source_type: string}) => row.source_type === "pubmed").review_status).toBe("reviewed");
    await page.getByRole("tab", { name: "Ask", exact: true }).click();
    await expect(page.locator(".conversation-turn")).toHaveCount(2);
    const savedTurn = page.locator(".conversation-turn").filter({ hasText: "Explain that more simply" });
    await savedTurn.locator("summary").click();
    await savedTurn.getByRole("button", { name: "Continue conversation", exact: true }).click();
    await expect(page.getByLabel("Sources for this conversation")).toHaveValue("pubmed");
    await expect(page.getByLabel("Ask a follow-up")).toBeVisible();
    await page.getByLabel("Sources for this conversation").selectOption("clinical_trials");
    await expect(page.locator("#answer-result")).toHaveCount(0);
    await page.locator("#ask-question").fill("What study is planned?");
    const changedResponse = page.waitForResponse(response => response.url().endsWith("/ask") && response.request().method() === "POST");
    await page.getByRole("button", { name: "Answer with citations", exact: true }).click();
    const changed = await (await changedResponse).json();
    expect(changed.previous_answer_id).toBeNull();
    expect(changed.source_types).toEqual(["clinical_trials"]);
    expect(changed.citations).toEqual(["ClinicalTrials.gov:EVAL-FILTER-PROTOCOL"]);
    await page.getByRole("tab", { name: "Brief", exact: true }).click();
    await page.getByRole("button", { name: "Remove from brief", exact: true }).click();
    await expect(page.locator(".brief-saved-answer")).toHaveCount(0);
    await expect(page.getByRole("button", { name: "Export brief", exact: true })).toBeDisabled();
    expect((await (await page.request.get(`${base}/brief`)).json()).saved_answers).toEqual([]);
  });

  test("keeps treatment and ambiguous-reference guards visible and starts a clean conversation", async ({ page }) => {
    await page.goto("/");
    await page.locator(".recent-workspace-button").first().click();
    await expect(page.locator(".workspace-context")).toBeVisible();
    await page.getByRole("tab", { name: "Ask", exact: true }).click();
    await page.locator("#ask-question").fill("Should I stop taking my medication?");
    const treatmentResponse = page.waitForResponse(response => response.url().endsWith("/ask") && response.request().method() === "POST");
    await page.getByRole("button", { name: "Answer with citations", exact: true }).click();
    const guarded = await (await treatmentResponse).json();
    expect(guarded.generation_note).toContain("Individual treatment decision; no model generation");
    await expect(page.locator("#answer-result")).toContainText(/clinician|treatment|medical advice/i);
    await page.getByRole("button", { name: "New conversation", exact: true }).click();
    await expect(page.locator("#answer-result")).toHaveCount(0);
    await expect(page.locator("#ask-question")).toHaveValue("");
    await page.locator("#ask-question").fill("Is it better than the other one?");
    const ambiguousResponse = page.waitForResponse(response => response.url().endsWith("/ask") && response.request().method() === "POST");
    await page.getByRole("button", { name: "Answer with citations", exact: true }).click();
    const ambiguous = await (await ambiguousResponse).json();
    expect(ambiguous.previous_answer_id).toBeNull();
    expect(ambiguous.generation_note).toContain("Clarification needed; no model generation");
    await expect(page.locator("#answer-result")).toContainText(/which|specific|clarif|name/i);
    await expect(page.getByLabel("Ask a follow-up")).toBeVisible();
  });
});
